export function getLanguage(): LanguageCode {
  const selected = typeof localStorage !== "undefined" ? localStorage.getItem("reformany.language") : null;
  return LANGUAGE_OPTIONS.some(item=>item.code === selected) ? selected as LanguageCode : "en";
}
export function t(language: LanguageCode,key: LangKey): string {
  const at=LANG_KEYS.indexOf(key);
  return messages[language]?.[at] || messages.en[at] || key;
}
export function setDocumentLanguage(language:LanguageCode):void {
  document.documentElement.lang=language === "zh" ? "zh-CN" : language;
  document.documentElement.dir=RTL_LANGUAGES.has(language) ? "rtl" : "ltr";
  document.documentElement.dataset.direction = RTL_LANGUAGES.has(language) ? "rtl" : "ltr";
}
